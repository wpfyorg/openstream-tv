#!/usr/bin/env python3
"""Copy the WTFM articles into the Svelte docs site.

`docs/` stays the single source of truth: this script mirrors every
`docs/<slug>/index.md` into `docs-site/src/content/docs/`, moves the
screenshots into `docs-site/static/images/`, rewrites the relative
`../<slug>/index.md` links into routes, and regenerates the sidebar from
`docs/SUMMARY.md`.

Run it before `bun run dev` or `bun run build` in `docs-site`, or through
`bun run sync:content`, which the docs workflow does for you.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
docs = repo / "docs"
site = repo / "docs-site"
content = site / "src/content/docs"
images = docs / "images"
sidebar_file = site / "src/lib/docs/sidebar.generated.ts"

# Authored links point at the next article's source file; the site needs its
# route instead. Pages are emitted with a trailing slash, so siblings resolve
# as `../<slug>/` from an article and `./<slug>/` from the help-centre home.
slug_link = re.compile(r"\]\(\.\./([a-z0-9-]+)/index\.md\)")
image_link = re.compile(r"\]\(\.\./images/([^)]+)\)")


def copy_articles() -> int:
    shutil.rmtree(content, ignore_errors=True)
    content.mkdir(parents=True)

    count = 0
    for article in sorted(docs.glob("*/index.md")):
        slug = article.parent.name
        text = article.read_text(encoding="utf-8")
        if slug == "help-centre":
            text = slug_link.sub(lambda m: f"](./{m.group(1)}/)", text)
            text = image_link.sub(lambda m: f"](../images/{m.group(1)})", text)
            text = text.replace(
                "[Browse all articles](../SUMMARY.md) · [Documentation home](../README.md)",
                "[Browse all articles](./getting-started/)",
            )
            # Keep the Markdown link syntax: only the destination changes.
            text = text.replace("](./help-centre/)", "](./)")
            target = content / "index.md"
        else:
            text = slug_link.sub(lambda m: f"](../{m.group(1)}/)", text)
            text = image_link.sub(lambda m: f"](../../images/{m.group(1)})", text)
            # The help centre is the docs home now, not a separate article.
            text = text.replace("](../help-centre/)", "](../)")
            target = content / f"{slug}.md"
        # The page header already renders the title from the frontmatter, so a
        # leading `# Title` in the body would duplicate the <h1>.
        _, _, body = text.partition("\n---\n")
        if body:
            text = text[: len(text) - len(body)] + re.sub(r"^\s*# [^\n]*\n", "", body, count=1)
        target.write_text(text, encoding="utf-8")
        count += 1
    return count


def copy_images() -> int:
    dest = site / "static/images"
    shutil.rmtree(dest, ignore_errors=True)
    if not images.is_dir():
        return 0
    dest.mkdir(parents=True)
    for image in images.iterdir():
        if image.is_file():
            shutil.copy2(image, dest / image.name)
    return len(list(dest.iterdir()))


section_re = re.compile(r"^##\s+(?P<label>.+?)\s*$")
item_re = re.compile(r"^\s*-\s+\[(?P<label>[^\]]+)\]\((?P<target>[a-z0-9-]+)/index\.md\)\s*$")


def write_sidebar() -> int:
    sections: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    for line in (docs / "SUMMARY.md").read_text(encoding="utf-8").splitlines():
        heading = section_re.match(line)
        if heading:
            current = {"label": heading.group("label"), "items": []}
            sections.append(current)
            continue
        item = item_re.match(line)
        if item and current is not None:
            current["items"].append(  # type: ignore[union-attr]
                {
                    "label": item.group("label"),
                    "href": f"/docs/{item.group('target')}",
                }
            )

    lines = [
        "// Generated by scripts/build-docs-site.py from docs/SUMMARY.md.",
        "// Do not edit by hand: change the article list in docs/SUMMARY.md.",
        "",
        "export const sidebarSections: { label: string; items: { label: string; href: string }[] }[] = [",
    ]
    for section in sections:
        if not section["items"]:
            continue
        lines.append(f"  {{\n    label: {str(section['label'])!r},")
        lines.append("    items: [")
        for item in section["items"]:  # type: ignore[union-attr]
            lines.append(f"      {{ label: {item['label']!r}, href: {item['href']!r} }},")
        lines.append("    ],\n  },")
    lines.append("];\n")
    sidebar_file.write_text("\n".join(lines), encoding="utf-8")
    return sum(len(s["items"]) for s in sections)  # type: ignore[arg-type]


def main() -> int:
    articles = copy_articles()
    image_count = copy_images()
    nav_items = write_sidebar()
    print(f"docs-site: mirrored {articles} articles, {image_count} images, {nav_items} sidebar entries")
    if "--sync-only" in sys.argv[1:]:
        return 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
